function estimateWalkMinutes(codeA, codeB, roomA, roomB) {
  if (!codeA || !codeB) return null;
  if (codeA === codeB) return roomA && roomB && roomA === roomB ? 1 : 2;
  const za = BUILDING_ZONE[codeA], zb = BUILDING_ZONE[codeB];
  if (za == null || zb == null) return 12; // ZONE 정보 없는 건물(밀양/양산 등) - 넉넉히 추정
  const diff = Math.abs(za - zb);
  if (diff === 0) return 4;
  if (diff === 1) return 7;
  if (diff === 2) return 10;
  return 14;
}

function walkLevel(gapMin, walkMin) {
  if (gapMin < walkMin) return "danger";
  if (gapMin < walkMin + 3) return "warn";
  return "ok";
}
